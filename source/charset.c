#include "charset.h"

// Code page 850's upper half, 0x80-0xFF, folded to ASCII
static const char cp850_ascii[128] = {
	'C', 'u', 'e', 'a', 'a', 'a', 'a', 'c', 'e', 'e', 'e', 'i', 'i', 'i', 'A', 'A', // 0x80
	'E', 'a', 'A', 'o', 'o', 'o', 'u', 'u', 'y', 'O', 'U', 'o', 'L', 'O', 'x', 'f', // 0x90
	'a', 'i', 'o', 'u', 'n', 'N', 'a', 'o', '?', 'R', '-', '?', '?', '!', '"', '"', // 0xA0
	'?', '?', '?', '?', '?', 'A', 'A', 'A', 'C', '?', '?', '?', '?', 'c', 'Y', '?', // 0xB0
	'?', '?', '?', '?', '?', '?', 'a', 'A', '?', '?', '?', '?', '?', '?', '?', 'o', // 0xC0
	'd', 'D', 'E', 'E', 'E', 'i', 'I', 'I', 'I', '?', '?', '?', '?', '|', 'I', '?', // 0xD0
	'O', 's', 'O', 'O', 'o', 'O', 'u', 'p', 'P', 'U', 'U', 'U', 'y', 'Y', '-', '\'', // 0xE0
	'-', '+', '_', '?', 'P', 'S', '/', ',', 'o', '"', '.', '1', '3', '2', '?', ' ', // 0xF0
};

char charset_ascii(u8 c)
{
	if (c < 0x80)
		return c;
	return cp850_ascii[c - 0x80];
}
